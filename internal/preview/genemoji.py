#!/usr/bin/env python3
"""Cut Noto Color Emoji into the pictures the preview cards draw emoji with.

Writes emoji.zip, one PNG per emoji sequence, and emoji_presentation.go,
Unicode's Emoji_Presentation table, beside this script. Run it again when
the font or Unicode's emoji data moves on:

    python3 -m venv /tmp/genemoji && /tmp/genemoji/bin/pip install fonttools uharfbuzz
    /tmp/genemoji/bin/python internal/preview/genemoji.py

Every picture is the font's own PNG, byte for byte: Noto's are already
packed tighter than any re-encoding of them (a smaller size, a palette or
WebP each came out larger or lost colour), and the card scales them as it
draws. A picture is named by its sequence's code points in lowercase hex
joined by "-", less U+FE0F, which the card skips when it matches — so
"❤️‍🔥" (2764 FE0F 200D 1F525) is 2764-200d-1f525.png.

Which sequence is which picture is HarfBuzz's answer, not a reading of
the font's GSUB: every sequence in Unicode's emoji-test.txt, with and
without its U+FE0F, shaped with the font, kept when it comes out as one
picture; then every character the font maps on its own.
"""

import argparse
import os
import sys
import tempfile
import urllib.request
import zipfile

import uharfbuzz as hb
from fontTools.ttLib import TTFont

HERE = os.path.dirname(os.path.abspath(__file__))
UNICODE = "16.0"
SOURCES = {
    "emoji-test.txt": f"https://www.unicode.org/Public/emoji/{UNICODE}/emoji-test.txt",
    "emoji-data.txt": f"https://www.unicode.org/Public/{UNICODE}.0/ucd/emoji/emoji-data.txt",
}
# The box emoji.go draws every picture in: the font's one strike. A font
# that breaks it needs emoji.go's constants changed with it.
PPEM, ASCENT, DESCENT, WIDTH, HEIGHT = 109, 101, -27, 136, 128


def fetch(dir):
    for name, url in SOURCES.items():
        path = os.path.join(dir, name)
        if not os.path.exists(path):
            urllib.request.urlretrieve(url, path)


def sequences(path):
    for line in open(path, encoding="utf-8"):
        if line.startswith("#") or ";" not in line:
            continue
        yield [int(cp, 16) for cp in line.split(";")[0].split()]


def presentation(path):
    """Emoji_Presentation as merged ranges."""
    ranges = []
    for line in open(path, encoding="utf-8"):
        line = line.split("#")[0].strip()
        if not line or line.split(";")[1].strip() != "Emoji_Presentation":
            continue
        span = line.split(";")[0].strip()
        lo, _, hi = span.partition("..")
        lo, hi = int(lo, 16), int(hi or lo, 16)
        if ranges and ranges[-1][1] + 1 == lo:
            ranges[-1][1] = hi
        else:
            ranges.append([lo, hi])
    return ranges


def write_go(ranges, path):
    r16 = [r for r in ranges if r[1] <= 0xFFFF]
    r32 = [r for r in ranges if r[0] > 0xFFFF]
    assert len(r16) + len(r32) == len(ranges), "a range straddles U+FFFF"
    out = [
        f"// Code generated by genemoji.py from Unicode {UNICODE}'s emoji-data.txt; DO NOT EDIT.",
        "",
        "package preview",
        "",
        'import "unicode"',
        "",
        "// emojiPresentation is Unicode's Emoji_Presentation: the characters an",
        "// emoji picture stands for with no U+FE0F after them.",
        "var emojiPresentation = &unicode.RangeTable{",
        "\tR16: []unicode.Range16{",
        *[f"\t\t{{0x{lo:04x}, 0x{hi:04x}, 1}}," for lo, hi in r16],
        "\t},",
        "\tR32: []unicode.Range32{",
        *[f"\t\t{{0x{lo:x}, 0x{hi:x}, 1}}," for lo, hi in r32],
        "\t},",
        "}",
        "",
    ]
    with open(path, "w", encoding="utf-8") as f:
        f.write("\n".join(out))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--font", default="/usr/share/fonts/truetype/noto/NotoColorEmoji.ttf")
    ap.add_argument("--unicode", help="a directory holding emoji-test.txt and emoji-data.txt (fetched when missing)")
    args = ap.parse_args()
    udir = args.unicode or tempfile.mkdtemp(prefix="genemoji-")
    fetch(udir)

    tt = TTFont(args.font)
    strikes = tt["CBLC"].strikes
    assert len(strikes) == 1, "more than one strike"
    m = strikes[0].bitmapSizeTable
    assert (m.ppemY, m.hori.ascender, m.hori.descender) == (PPEM, ASCENT, DESCENT), "the strike moved"
    pictures = tt["CBDT"].strikeData[0]
    for name, g in pictures.items():
        gm = g.metrics
        if (gm.width, gm.height, gm.BearingX, gm.BearingY, gm.Advance) != (WIDTH, HEIGHT, 0, ASCENT, WIDTH):
            sys.exit(f"{name} is not in the common box: {vars(gm)}")
    order = tt.getGlyphOrder()

    font = hb.Font(hb.Face(hb.Blob.from_file_path(args.font)))

    def one(cps):
        buf = hb.Buffer()
        buf.add_codepoints(cps)
        buf.guess_segment_properties()
        buf.flags = hb.BufferFlags.REMOVE_DEFAULT_IGNORABLES
        hb.shape(font, buf, {})
        names = [order[i.codepoint] for i in buf.glyph_infos]
        return names[0] if len(names) == 1 and names[0] in pictures else None

    keys, missed = {}, []
    for cps in sequences(os.path.join(udir, "emoji-test.txt")):
        bare = [c for c in cps if c != 0xFE0F]
        name = one(cps) or one(bare)
        if name is None:
            missed.append(cps)
            continue
        keys.setdefault(tuple(bare), name)
    for cp, name in tt.getBestCmap().items():
        if name in pictures and cp != 0xFE0F:
            keys.setdefault((cp,), name)

    out = os.path.join(HERE, "emoji.zip")
    with zipfile.ZipFile(out, "w", zipfile.ZIP_STORED) as z:
        for key in sorted(keys):
            info = zipfile.ZipInfo("-".join(f"{cp:x}" for cp in key) + ".png", date_time=(1980, 1, 1, 0, 0, 0))
            z.writestr(info, pictures[keys[key]].imageData)
    ranges = presentation(os.path.join(udir, "emoji-data.txt"))
    write_go(ranges, os.path.join(HERE, "emoji_presentation.go"))

    print(f"{len(keys)} sequences, {len(set(keys.values()))} of the font's {len(pictures)} pictures, "
          f"{os.path.getsize(out) / 1e6:.1f} MB; {len(ranges)} Emoji_Presentation ranges")
    for cps in missed:
        print("no single picture for", " ".join(f"{c:04X}" for c in cps))


if __name__ == "__main__":
    main()
